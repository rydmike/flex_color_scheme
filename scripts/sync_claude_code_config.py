#!/usr/bin/env python3
"""Generate local Claude mirrors from this checkout's canonical guidance."""

from pathlib import Path
import os
import re
import shutil
import sys
import tempfile
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parent.parent
NOTICE = '<!-- Generated by scripts/sync_claude_code_config.sh; edit canonical AGENTS.md or .agents/skills/ and sync again. -->'
LINK = re.compile(r'(!?\[[^\]\n]*\]\()([^\s)]+)(\))')


def rewrite_links(text):
    """Rewrite link destinations only; preserve canonical-source prose."""
    def rewrite(match):
        target = match[2]
        if target.startswith('.agents/skills/'):
            target = '.claude/skills/' + target[len('.agents/skills/'):]
        else:
            target = target.replace('/.agents/skills/', '/.claude/skills/')
        return match[1] + target + match[3]
    return LINK.sub(rewrite, text)


def validate_links(path):
    for match in LINK.finditer(path.read_text()):
        target = match[2].strip('<>')
        if target.startswith('#') or re.match(r'[a-zA-Z][a-zA-Z0-9+.-]*:', target):
            continue
        target = unquote(target.split('#', 1)[0])
        if not (path.parent / target).exists():
            raise ValueError(f'Broken local link in {path.relative_to(ROOT)}: {target}')


def generated(text, skill_entry=False):
    text = rewrite_links(text)
    if skill_entry:
        # Preserve YAML frontmatter as the first bytes of SKILL.md.
        end = text.index('\n---', 4) + len('\n---')
        return text[:end] + '\n\n' + NOTICE + text[end:]
    return NOTICE + '\n\n' + text


def sync():
    agents = ROOT / 'AGENTS.md'
    source = ROOT / '.agents/skills'
    if not agents.is_file() or not source.is_dir():
        raise ValueError('Both AGENTS.md and .agents/skills/ are required.')
    skills = sorted(p for p in source.iterdir() if p.is_dir())
    if not skills:
        raise ValueError('No canonical skill directories found.')
    validate_links(agents)
    for skill in skills:
        entry = skill / 'SKILL.md'
        if not entry.is_file():
            raise ValueError(f'Missing SKILL.md in {skill.name}')
        text = entry.read_text()
        front = re.match(r'\A---\n(.*?)\n---(?:\n|$)', text, re.S)
        if not front:
            raise ValueError(f'Missing YAML frontmatter in {skill.name}')
        name = re.search(r'^name:\s*([^\n]+)$', front[1], re.M)
        description = re.search(r'^description:\s*([^\n]+)$', front[1], re.M)
        if not name or name[1].strip(' \"\'') != skill.name or not description:
            raise ValueError(f'Invalid name/description in {skill.name}')
        for markdown in skill.rglob('*.md'):
            validate_links(markdown)

    claude = ROOT / '.claude'
    target = claude / 'skills'
    guide = ROOT / 'CLAUDE.md'
    for path in (claude, target, guide):
        if path.is_symlink():
            raise ValueError(f'Refusing symlinked output: {path}')
    if target.exists() and not target.is_dir():
        raise ValueError('.claude/skills must be a directory.')
    if guide.exists() and not guide.is_file():
        raise ValueError('CLAUDE.md must be a regular file.')

    claude.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.sync-', dir=claude) as staging:
        stage = Path(staging)
        prepared = stage / 'skills'
        prepared.mkdir()
        for skill in skills:
            copy = prepared / skill.name
            shutil.copytree(skill, copy)
            for markdown in copy.rglob('*.md'):
                markdown.write_text(generated(markdown.read_text(), markdown == copy / 'SKILL.md'))
        prepared_guide = stage / 'CLAUDE.md'
        prepared_guide.write_text(generated(agents.read_text()))
        # All generation completes before existing mirrors are replaced.
        backup = stage / 'previous-skills'
        had_skills = target.exists()
        if had_skills:
            target.rename(backup)
        try:
            prepared.rename(target)
            os.replace(prepared_guide, guide)
        except OSError:
            if target.exists():
                shutil.rmtree(target)
            if had_skills:
                backup.rename(target)
            raise
    print(f'Claude Code config synced: CLAUDE.md and .claude/skills/ ({len(skills)} skills).')


if __name__ == '__main__':
    try:
        sync()
    except (OSError, ValueError) as error:
        print(f'Error: {error}', file=sys.stderr)
        sys.exit(1)
